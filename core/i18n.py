def get_lang() -> str:
    """Return the active language code from session state."""
    try:
        lang = st.session_state.get("lang", _DEFAULT_LANG)
        return lang if lang in _SUPPORTED_LANGS else _DEFAULT_LANG
    except Exception:
        return _DEFAULT_LANG


def set_lang(lang: str) -> None:
    """Persist language choice in session state."""
    if lang in _SUPPORTED_LANGS:
        st.session_state["lang"] = lang


def t(key: str, **kwargs: str) -> str:
    """
    Translate *key* for the current UI language.
    Falls back to English, then the raw key if still missing.
    Supports named format placeholders: t("msg.hello", name="World")
    """
    lang = get_lang()
    text: str | None = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS.get("en", {}).get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text
